/**
 * Generates data/reference/beyond-panel.json: SYNTHETIC shared segment data for the demo couples.
 *
 * This is NOT the output of a genomics pipeline. No genomes were simulated and no ROH or kinship
 * tool was run. The segments are drawn by a seeded random generator so that the total shared
 * length is plausible for the couple's stated relationship (first cousins share about a quarter
 * of the autosomes on one copy; unrelated people share almost nothing). The real pipeline
 * (msprime, bcftools roh, KING) belongs to the genomics service, which needs Azure.
 *
 * Run: node scripts/gen-beyond-panel.cjs
 */
// eslint-disable-next-line @typescript-eslint/no-require-imports
const fs = require("fs");
const CHR = { 1: 248, 2: 242, 3: 198, 4: 190, 5: 182, 6: 171, 7: 159, 8: 145, 9: 138, 10: 134, 11: 135, 12: 133, 13: 114, 14: 107, 15: 102, 16: 90, 17: 83, 18: 80, 19: 59, 20: 64, 21: 47, 22: 51 };
const GENOME = Object.values(CHR).reduce((a, b) => a + b, 0);

function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Non overlapping segments whose total is close to `share` of the genome. */
function segments(seed, share, meanMb) {
  const r = rng(seed);
  const target = share * GENOME;
  const out = [];
  let total = 0;
  let guard = 0;
  while (total < target && guard++ < 5000) {
    const chr = 1 + Math.floor(r() * 22);
    const len = Math.max(3, Math.min(CHR[chr] * 0.6, -Math.log(1 - r()) * meanMb));
    const start = Math.round(r() * (CHR[chr] - len) * 10) / 10;
    const end = Math.round((start + Math.min(len, target - total + 2)) * 10) / 10;
    if (end - start < 2) continue;
    if (out.some((s) => s.chr === chr && start < s.endMb + 1 && end > s.startMb - 1)) continue;
    out.push({ chr, startMb: start, endMb: end });
    total += end - start;
  }
  return out.sort((a, b) => a.chr - b.chr || a.startMb - b.startMb);
}

const data = {
  _about:
    "SYNTHETIC, illustrative data for the prototype. Not the output of a genomics pipeline: no genomes were simulated and no ROH or kinship tool was run. Generated by scripts/gen-beyond-panel.cjs with a fixed seed.",
  generator: "scripts/gen-beyond-panel.cjs",
  couples: {
    "khalid-mariam": { declared: "first_cousins", shared: segments(20261115, 0.262, 32) },
    "faisal-noura": { declared: "unrelated", shared: segments(77, 0.004, 4) },
  },
};
fs.writeFileSync("data/reference/beyond-panel.json", JSON.stringify(data, null, 1) + "\n");
for (const [k, v] of Object.entries(data.couples)) {
  const mb = v.shared.reduce((n, s) => n + s.endMb - s.startMb, 0);
  console.log(k, v.shared.length, "segments,", mb.toFixed(1), "Mb, kinship", (mb / GENOME / 4).toFixed(4));
}
